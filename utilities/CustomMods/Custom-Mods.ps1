[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [ValidateSet('Save', 'Restore')]
    [string]$Action
)

$ErrorActionPreference = 'Stop'
$gammaRoot = Split-Path (Split-Path $PSScriptRoot -Parent) -Parent
$profileName = 'G.A.M.M.A'
$profileModlist = Join-Path $gammaRoot "profiles\$profileName\modlist.txt"
$installerModlist = Join-Path $gammaRoot ".Grok's Modpack Installer\G.A.M.M.A\modpack_data\modlist.txt"
$savedList = Join-Path $PSScriptRoot 'custom-active-mods.txt'
$backupDir = Join-Path $PSScriptRoot 'backups'
$separatorName = '0000- MY CUSTOM MODS_separator'
$separatorDir = Join-Path $gammaRoot "mods\$separatorName"

function Stop-IfMo2IsRunning {
    if (Get-Process -Name 'ModOrganizer' -ErrorAction SilentlyContinue) {
        throw 'Mod Organizer 2 is running. Close MO2 completely and run this file again.'
    }
}

function Read-ModNames([string]$Path) {
    Get-Content -LiteralPath $Path -Encoding UTF8 |
        Where-Object { $_ -match '^[+-].+' } |
        ForEach-Object { $_.Substring(1) }
}

function Backup-Modlist {
    New-Item -ItemType Directory -Path $backupDir -Force | Out-Null
    $stamp = Get-Date -Format 'yyyy-MM-dd_HH-mm-ss'
    Copy-Item -LiteralPath $profileModlist -Destination (Join-Path $backupDir "modlist_$stamp.txt")
}

function Write-Utf8Bom([string]$Path, [string[]]$Lines) {
    $encoding = [System.Text.UTF8Encoding]::new($true)
    [System.IO.File]::WriteAllLines($Path, $Lines, $encoding)
}

function Put-CustomModsAtTop([string[]]$CustomNames) {
    $customSet = [Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
    $CustomNames | ForEach-Object { [void]$customSet.Add($_) }

    $oldLines = @(Get-Content -LiteralPath $profileModlist -Encoding UTF8)
    $rest = @($oldLines | Where-Object {
        if ($_ -notmatch '^[+-](.+)$') { return $false }
        $name = $Matches[1]
        return $name -ne $separatorName -and -not $customSet.Contains($name)
    })

    $newLines = @('# This file was automatically generated by Mod Organizer.')
    $newLines += @($CustomNames | ForEach-Object { "+$_" })
    $newLines += "+$separatorName"
    $newLines += $rest
    Write-Utf8Bom -Path $profileModlist -Lines $newLines
}

Stop-IfMo2IsRunning
if (-not (Test-Path -LiteralPath $profileModlist)) {
    throw "Profile mod list not found: $profileModlist"
}

New-Item -ItemType Directory -Path $separatorDir -Force | Out-Null

if ($Action -eq 'Save') {
    if (-not (Test-Path -LiteralPath $installerModlist)) {
        throw "GAMMA installer mod list not found: $installerModlist"
    }

    $official = [Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
    Read-ModNames $installerModlist | ForEach-Object { [void]$official.Add($_) }

    $custom = @(Get-Content -LiteralPath $profileModlist -Encoding UTF8 |
        Where-Object { $_ -like '+*' } |
        ForEach-Object { $_.Substring(1) } |
        Where-Object { $_ -ne $separatorName -and -not $official.Contains($_) })

    Backup-Modlist
    Write-Utf8Bom -Path $savedList -Lines $custom
    Put-CustomModsAtTop -CustomNames $custom
    Write-Host "Saved and grouped $($custom.Count) active custom mods." -ForegroundColor Green
    Write-Host "Snapshot: $savedList"
}
else {
    if (-not (Test-Path -LiteralPath $savedList)) {
        throw 'No saved custom-mod snapshot. Run SAVE before updating GAMMA.'
    }

    $saved = @(Get-Content -LiteralPath $savedList -Encoding UTF8 | Where-Object { $_.Trim() })
    $existingFolders = [Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
    Get-ChildItem -LiteralPath (Join-Path $gammaRoot 'mods') -Directory |
        ForEach-Object { [void]$existingFolders.Add($_.Name) }
    $available = @($saved | Where-Object { $existingFolders.Contains($_) })
    $missing = @($saved | Where-Object { -not $existingFolders.Contains($_) })

    Backup-Modlist
    Put-CustomModsAtTop -CustomNames $available
    Write-Host "Restored and grouped $($available.Count) active custom mods." -ForegroundColor Green
    if ($missing.Count) {
        Write-Warning ("Missing mod folders (not enabled): " + ($missing -join ', '))
    }
}

Write-Host 'Done. You can start MO2 now.'
Read-Host 'Press Enter to close'
